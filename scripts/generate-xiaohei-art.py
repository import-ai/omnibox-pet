#!/usr/bin/env python3
"""Generate Sources/XiaoheiArt.swift from the selected Xiaohei front-view SVG.

Usage:
    python3 scripts/generate-xiaohei-art.py <path-to-xiaohei-front-v14.svg>
    python3 scripts/generate-xiaohei-art.py <svg> --check   # verify the checked-in file
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Sources" / "XiaoheiArt.swift"
PATH_IDS = {
    "earRight": "ear-right",
    "earLeft": "ear-left",
    "head": "head-outline",
    "eyeWhite": "eye-white-right",
    "pupil": "pupil-right",
}


def path_attr(svg: str, path_id: str, attr: str) -> str:
    for tag in re.findall(r"<path\b[^>]*>", svg):
        if re.search(r'\bid="%s"' % re.escape(path_id), tag):
            m = re.search(r'\b%s="([^"]+)"' % attr, tag)
            if not m:
                raise SystemExit(f"{path_id} has no {attr}")
            return m.group(1)
    raise SystemExit(f"path {path_id} not found")


def compact(d: str) -> str:
    # Three decimals on a 640-unit canvas is far below one screen pixel at any pet size.
    def fmt(m):
        return ("%.3f" % float(m.group())).rstrip("0").rstrip(".")
    return re.sub(r"-?\d+\.\d+", fmt, d)


def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        raise SystemExit(__doc__)
    svg = Path(args[0]).read_text()
    if 'viewBox="0 0 640 640"' not in svg:
        raise SystemExit("unexpected viewBox; expected the V14 640x640 canvas")

    eye_tf = path_attr(svg, "eye-white-right", "transform")
    pupil_tf = path_attr(svg, "pupil-right", "transform")
    if eye_tf != pupil_tf:
        raise SystemExit("eye white and pupil transforms differ; update the generator")
    m = re.fullmatch(r"matrix\(([^)]+)\)", eye_tf.strip())
    if not m:
        raise SystemExit("unexpected right-eye transform: " + eye_tf)
    a, b, c, d, e, f = (float(x) for x in m.group(1).split())
    for side in ("eye-white-left", "pupil-left"):
        if not path_attr(svg, side, "transform").startswith("translate(640 0) scale(-1 1) matrix("):
            raise SystemExit(f"{side} is no longer a mirror of the right eye; update the generator")

    lines = [
        "// GENERATED by scripts/generate-xiaohei-art.py — do not edit by hand.",
        "// Source: Xiaohei front-view SVG.",
        "// Coordinates are in the original 640x640 SVG canvas; the left eye mirrors the right eye around x=320.",
        "import CoreGraphics",
        "",
        "enum XiaoheiArt {",
    ]
    for name, pid in PATH_IDS.items():
        lines.append(f'    static let {name}D = "{compact(path_attr(svg, pid, "d"))}"')
    lines += [
        f"    static let rightEyeTransform = CGAffineTransform(a: {a!r}, b: {b!r}, c: {c!r}, d: {d!r}, tx: {e!r}, ty: {f!r})",
        "}",
        "",
    ]
    text = "\n".join(lines)
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            raise SystemExit(f"{OUT} is stale; rerun the generator")
        print("XiaoheiArt.swift is up to date")
        return
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
